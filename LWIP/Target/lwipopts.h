/* Increase TCP buffers for large TLS 1.3 + X9.146 handshake flights.
 * ML-DSA-44  server flight ~  8 KB  -> fits 16 KB heap
 * ML-DSA-65  server flight ~ 15 KB  -> fits 16 KB heap (tight)
 * ML-DSA-87  server flight ~ 22 KB  -> needs >=24 KB heap + ~24 KB SND_BUF
 * So we now run on a 24 KB heap (heap pointer moved to 0x30002000,
 * RX pool shrunk to 5 buffers). SND_BUF must be >= largest single
 * TLS record the stack can push (Certificate at L5 = 17.3 KB).         */
#define TCP_MSS                     1460
#define TCP_WND                     (12 * TCP_MSS)  /* 17520 B recv win  */
#define TCP_SND_BUF                 (16 * TCP_MSS)  /* 23360 B send buf  */
#define MEMP_NUM_TCP_SEG            64              /* must >= TCP_SND_QUEUELEN */
#define MEM_SIZE                    24000           /* LwIP heap in D2 (0x30002000..0x30008000) */

